#!/usr/bin/env python3
"""Embed the dashboard into a C translation unit (no xxd needed in the build image).

usage: embed_html.py web/index.html out.c [web/img/a.webp ...]

index.html becomes web_page_html[]. Every extra file becomes an entry of
web_assets[], served at /img/<basename> by web.c.
"""
import os, sys

MIME = {".webp": "image/webp", ".png": "image/png", ".jpg": "image/jpeg", ".svg": "image/svg+xml"}

def blob(f, name, data):
    f.write("static const unsigned char %s[] = {\n" % name)
    for i in range(0, len(data), 20):
        f.write("  " + ",".join("0x%02x" % b for b in data[i:i+20]) + ",\n")
    f.write("};\n")

src, dst, assets = sys.argv[1], sys.argv[2], sys.argv[3:]
# Always embed web/img/* beside index.html too, so a build that passes no
# asset list (or an empty one) still ships the images.
imgdir = os.path.join(os.path.dirname(os.path.abspath(src)), "img")
if os.path.isdir(imgdir):
    assets += [os.path.join(imgdir, n) for n in os.listdir(imgdir) if not n.startswith(".")]
assets = sorted({os.path.abspath(a): a for a in assets}.values(), key=os.path.basename)
# Every /img/<name> the page uses must be embedded, or the build fails here.
import re
html = open(src, encoding="utf-8").read()
have = {os.path.basename(a) for a in assets}
missing = sorted(set(re.findall(r"/img/([A-Za-z0-9_.-]+)", html)) - have)
if missing:
    sys.exit("embed_html.py: page references images that are not in web/img: " + ", ".join(missing))
with open(dst, "w") as f:
    f.write("/* Generated by tools/embed_html.py from %s. Do not edit. */\n" % src)
    f.write("#include <stddef.h>\n\n")
    data = open(src, "rb").read()
    f.write("const unsigned char web_page_html[] = {\n")
    for i in range(0, len(data), 20):
        f.write("  " + ",".join("0x%02x" % b for b in data[i:i+20]) + ",\n")
    f.write("};\nconst unsigned int web_page_html_len = %d;\n\n" % len(data))
    rows = []
    for i, a in enumerate(assets):
        base = os.path.basename(a)
        blob(f, "asset_%d" % i, open(a, "rb").read())
        rows.append((base, MIME.get(os.path.splitext(base)[1].lower(), "application/octet-stream"), "asset_%d" % i, os.path.getsize(a)))
    f.write("\ntypedef struct { const char *name, *mime; const unsigned char *data; unsigned int len; } web_asset_t;\n")
    f.write("const web_asset_t web_assets[] = {\n")
    for r in rows:
        f.write('  { "%s", "%s", %s, %d },\n' % r)
    f.write("  { 0, 0, 0, 0 }\n};\n")
